"""wcd_semantic must reproduce the upstream UVA code's output on the fixed corpus.

fixtures/golden/semantic/expected.json was generated by gen_golden.py from the
upstream modules at the commit recorded in NOTICE. Each test below runs the
identical assembly through the vendored package and compares.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from assemble import Backend, dumps, run_contents, run_flags, run_global, run_pages, run_scores, strip_added
from wcd_semantic import content, match_global, match_reftag, match_template, merge_types, reftag, scoring, signals, template

GOLDEN = json.loads((Path(__file__).resolve().parents[3] / "fixtures" / "golden" / "semantic" / "expected.json").read_text())


def ported_backend() -> Backend:
    return Backend(
        parse_citation=content.parse_citation, iter_citations=content.iter_citations,
        is_multi_block=content.is_multi_block, is_citation=content.is_citation,
        classify=reftag.classify, extract_template=template.extract_template,
        extract_flags=signals.extract_flags,
        reftag_match=lambda df, pid: match_reftag.match_page(df, pid)[:2],
        template_match=lambda df, pid: match_template.match_page(df, pid)[:2],
        normalize_key=merge_types._normalize_key, merge=merge_types.merge_page,
        global_match=lambda df: match_global.match_global(df)[:2],
        compute_score=scoring.compute_score,
    )


@pytest.fixture(scope="module")
def b() -> Backend:
    return ported_backend()


@pytest.fixture(scope="module")
def pages(b):
    return run_pages(b)


def _assert_same(actual, expected, label):
    actual = strip_added(actual)
    expected = strip_added(expected)   # upstream never had pmc on matcher outputs either way
    if actual != expected:
        a, e = dumps(actual).splitlines(), dumps(expected).splitlines()
        diff = [f"-{x}" if x not in a else f"+{x}" for x in e + a if (x not in a) or (x not in e)]
        pytest.fail(f"{label} differs from upstream golden:\n" + "\n".join(diff[:60]))


@pytest.mark.parametrize("i", range(len(GOLDEN["contents"])))
def test_content_classification(b, i):
    actual = run_contents(b)[i]      # cheap; classify is cached-free but the corpus is small
    _assert_same(actual, GOLDEN["contents"][i], f"contents[{i}] {GOLDEN['contents'][i]['content'][:60]!r}")


def test_revision_flags(b):
    _assert_same(run_flags(b), GOLDEN["flags"], "flags")


@pytest.mark.parametrize("page_id", sorted(GOLDEN["pages"]))
@pytest.mark.parametrize("table", ["reftag_input", "template_input", "sources", "citation_map", "template_sources", "template_map", "merged"])
def test_per_page_matching(pages, page_id, table):
    per_page, _, _ = pages
    _assert_same(per_page[page_id][table], GOLDEN["pages"][page_id][table], f"page {page_id} {table}")


def test_cross_page_matching(b, pages):
    _, merged_df, _ = pages
    _assert_same(run_global(b, merged_df), GOLDEN["global"], "global")


def test_scoring(b):
    _assert_same(run_scores(b), GOLDEN["scores"], "scores")


def test_corpus_covers_every_signal():
    """Guard against the corpus silently losing coverage when it is extended."""
    page_types = {s["match_type"] for p in GOLDEN["pages"].values() for s in p["sources"]}
    merged_types = {m["match_type"] for p in GOLDEN["pages"].values() for m in p["merged"]}
    global_types = {s["match_type"] for s in GOLDEN["global"]["global_sources"]}
    subtypes = {c["reftag"]["norm_subtype"] for c in GOLDEN["contents"]}
    assert {"anchor_key", "fuzzy", "ref_name", "singleton"} <= page_types
    assert {"isbn", "url", "doi", "author_year"} <= merged_types
    assert {"doi", "isbn", "author_year_fuzzy", "singleton"} <= global_types
    assert {"wikilink_ref", "bare_url", "shorthand_template", "author_date", "prose_citation",
            "noise", "italicized_citation", "cite_html"} <= subtypes
